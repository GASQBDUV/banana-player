#!/usr/bin/env python3
# Banana Player's icon: pixel art on a 32x32 grid (two yellow spirals round a play button, on a dark rounded square),
# scaled up without smoothing. Standard library only (zlib, struct): no Pillow needed.
#   make-icon.py OUT.png [SCALE]
import struct, sys, zlib

# ' ' clear (outside the rounded square), '.' the square, 'Y' the swirl, 'W' the play button
GRID = """
    ........................    
  ............................  
 .............YYYY............. 
 .........YYYYYYYYYYY.......... 
.........YYYYYY......YYY........
.......YYYYYY.....YY...YY.......
......YYYYY.......YYYYY..Y......
.....YYYYY........YYYYYY........
.....YYYY...........YYYYY.......
....YYYY..............YYYY......
....YYYY...............YYYY.....
....YYY.....WWW.........YYYY....
...YYYY.....WWWW........YYYY....
...YYYY.....WWWWWW.......YYY....
...YYYY.....WWWWWWWW.....YYYY...
...YYYY.....WWWWWWWWWW...YYYY...
...YYYY.....WWWWWWWWWW...YYYY...
...YYYY.....WWWWWWWW.....YYYY...
....YYY.....WWWWWW.......YYYY...
....YYYY....WWWW.........YYYY...
....YYYY....WWW..........YYY....
.....YYYY...............YYYY....
......YYYY..............YYYY....
.......YYYYY...........YYYY.....
........YYYYYY........YYYYY.....
......Y..YYYYY.......YYYYY......
.......YY...YY.....YYYYYY.......
........YYY......YYYYYY.........
 ..........YYYYYYYYYYY......... 
 .............YYYY............. 
  ............................  
    ........................    
"""
COLOURS = {".": (0x14, 0x13, 0x18, 255), "Y": (0xF8, 0xC2, 0x1C, 255), "W": (0xF7, 0xF4, 0xEA, 255), " ": (0, 0, 0, 0)}

rows = [r.ljust(32) for r in GRID.strip("\n").split("\n")]
assert len(rows) == 32 and all(len(r) == 32 for r in rows), "the grid is 32x32"

out = sys.argv[1]
s = int(sys.argv[2]) if len(sys.argv) > 2 else 16
raw = b"".join(b"\0" + b"".join(bytes(COLOURS[rows[y // s][x // s]]) for x in range(32 * s)) for y in range(32 * s))
chunk = lambda t, d: struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 32 * s, 32 * s, 8, 6, 0, 0, 0)) + \
	chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
open(out, "wb").write(png)
